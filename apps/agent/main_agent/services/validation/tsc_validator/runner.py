import subprocess
import tempfile
from pathlib import Path
from typing import Iterable

import structlog

from main_agent.services.validation._env import require_in_production
from main_agent.services.validation.finding import Finding
from main_agent.services.validation.safe_names import is_safe_artifact_name
from main_agent.services.validation.tsx_ast.catalog import ALLOWED_EXTENSION_IMPORTS

logger = structlog.get_logger(__name__)


_TSC_TIMEOUT_SECONDS = 10
_TSC_DIAGNOSTIC_RE = re.compile(
    r"^(?P<file>[^()]+)\((?P<line>\d+),(?P<col>\d+)\):\s+"
    r"error\s+TS(?P<code>\d+):\s+(?P<msg>.+)$"
)
_AGENT_SDK_GATE_DTS = Path(__file__).resolve().parent / "agent_sdk_gate.d.ts"

# Additive SDK subpath entries (mirror packages/exepad-sdk/src/entries/*.ts and
# the import-map keys in apps/runtime/client/index.html). These are stable
# architecture names, not symbols — the per-symbol routing lives in
# sdk-subpaths.json. Each is staged as a re-export of the bare gate module so
# tsc resolves ``@exepad/sdk/<entry>`` imports emitted by the split fixer.
_SDK_SUBPATH_ENTRIES: tuple[str, ...] = (
    "core",
    "charts",
    "motion",
    "forms",
    "overlays",
    "icons",
)


_TSCONFIG_TEMPLATE = {
    "compilerOptions": {
        "target": "ES2022",
        "module": "ESNext",
        "moduleResolution": "Bundler",
        "jsx": "react-jsx",
        "strict": True,
        # noImplicitAny is disabled — LLM-generated event handlers
        # commonly leave the event parameter untyped (``(e) => ...``).
        # The TS7006 false-positive cost a retry per affected component
        # in production; the safety gain (catching genuine type-confusion
        # bugs in agent-emitted code) is small relative to that cost.
        # strictNullChecks stays on (catches ``useModel().data`` null
        # bugs and similar real issues).
        "noImplicitAny": False,
        "noEmit": True,
        "skipLibCheck": True,
        "esModuleInterop": True,
        "allowSyntheticDefaultImports": True,
        "isolatedModules": True,
        "lib": ["ES2022", "DOM", "DOM.Iterable"],
    },
    "include": ["./*.tsx", "./*.ts", "./*.d.ts"],
}


# Minimal React types so ``"jsx": "react-jsx"`` doesn't error with
# ``Cannot find module 'react/jsx-runtime'`` (TS2875) or
# ``no interface 'JSX.IntrinsicElements' exists`` (TS7026) on every
# component. We don't ship ``@types/react`` in the agent container —
# the gate's value is checking ``useModel`` / ``useHandler`` /
# ``setState`` / ``Icons.*`` against the per-app manifest, not
# validating that ``<div>`` accepts ``className``. Making everything
# ``any`` here strips JSX type-checking but keeps the cross-reference
# checks intact (those run on identifiers in expressions, not on JSX).
