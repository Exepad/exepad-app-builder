# Shorthand ambient declarations for the vetted runtime extension packages
# (``@exepad/ext-three`` etc.). A body-less ``declare module "X";`` makes the
# whole module ``any`` — so ``import * as THREE from "@exepad/ext-three"`` and
# any member access (``THREE.WebGLRenderer``, ``THREE.Raycaster``, …) type-check
# without TS2307 ("cannot find module") or TS2339 ("property does not exist").
# This mirrors the runtime reality: ``packages/exepad-sdk/src/ext.d.ts`` types
# every extension member as ``any`` too. Built from the SAME allow-list the AST
# import rule uses (``ALLOWED_EXTENSION_IMPORTS``) so the gate and the rule can
# never disagree about which extensions are admissible.
_EXT_SHIM_DTS = (
    "// Auto-generated by tsc_validator/runner.py — do not edit by hand.\n"
    "// Ambient `any` modules for the vetted @exepad/ext-* extension packages.\n"
    + "".join(f'declare module "{spec}";\n' for spec in sorted(ALLOWED_EXTENSION_IMPORTS))
)


def run_tsc_check(
    *,
    tsx: str,
    component_name: str,
    app_dts: str,
    sibling_modules: dict[str, str] | None = None,
) -> list[Finding]:
    """Run ``tsc --noEmit`` against ``tsx`` + ``app_dts``.

    Args:
        tsx: Component source. Saved as ``<component_name>.tsx``.
        component_name: PascalCase identifier — also the file basename.
        app_dts: Generated per-app declaration file (from
            :func:`dts_generator.generate_app_dts`).
        sibling_modules: Optional Babel-shell sibling map
            ``{ModuleName: tsx_source}``. When provided, each sibling is
            staged as ``<ModuleName>.tsx`` in the same tmpdir so that
            ``import { X } from "./ModuleName"`` references resolve
            naturally and don't surface as TS2307 false positives. The
            target component's own name is filtered out defensively
            (passing the target in the dict is harmless). Findings from
            sibling files are filtered by ``_parse_diagnostics`` (which
            already restricts to the target file's diagnostics) so
            sibling-internal type errors don't leak into the gate.

    Returns:
        List of :class:`Finding`. Each TS diagnostic that survives the
        skip-lib pass becomes one Finding with rule_id
        ``"tsc.<TS-code>"`` and severity ``"error"``. Empty list when
        ``tsc`` isn't available, when both inputs are empty, or when
        the SDK type bundle can't be located.
    """
    if not tsx.strip():
        return []

    if not _AGENT_SDK_GATE_DTS.is_file():
        logger.warning(
            "tsc_validator: agent_sdk_gate.d.ts not found — skipping tsc gate",
            expected=str(_AGENT_SDK_GATE_DTS),
        )
        return []

    # Path-traversal guard: component_name is an LLM-controlled free-form string
    # that becomes a filename on disk. A name like `../../../../tmp/pwned` would
    # escape the tempdir. Skip the tsc gate (fail open on validation) rather than
    # write outside it — the save path rejects the name hard at artifact_tools.
    if not is_safe_artifact_name(component_name):
        logger.warning(
            "tsc_validator: unsafe component name, skipping tsc gate",
            name=component_name,
        )
        return []

    with tempfile.TemporaryDirectory(prefix="tsc-gate-") as tmpdir:
        tmp = Path(tmpdir)
        component_path = tmp / f"{component_name}.tsx"
        component_path.write_text(tsx, encoding="utf-8")
        (tmp / "app.d.ts").write_text(app_dts, encoding="utf-8")
        # React/JSX shim (+ extension ambient modules) — picked up by
        # tsconfig's ``"include": ["./*.d.ts"]``. Without the React shim tsc
        # errors with TS2875 / TS7026 on every component; the ``@exepad/ext-*``
        # ambient ``any`` modules let 3D/WebGL components import Three.js etc.
        # without TS2307 (same allow-list as the AST import rule).
        (tmp / "react-shim.d.ts").write_text(_REACT_SHIM_DTS + _EXT_SHIM_DTS, encoding="utf-8")

        # Stage Babel-shell siblings so ``import { X } from "./Sibling"``
        # resolves on disk instead of surfacing as TS2307. The target
        # itself is filtered out so we never overwrite the file we just
        # wrote at component_path. Sibling-internal type errors are
        # filtered out downstream by _parse_diagnostics, which restricts
        # findings to the target file's diagnostics.
        for sib_name, sib_tsx in (sibling_modules or {}).items():
            if sib_name == component_name:
                continue
            if not isinstance(sib_name, str) or not isinstance(sib_tsx, str):
                continue
            # Same traversal guard for sibling names before they hit the disk.
            if not is_safe_artifact_name(sib_name):
                continue
            if not sib_tsx.strip():
                continue
            (tmp / f"{sib_name}.tsx").write_text(sib_tsx, encoding="utf-8")

        # Stage the curated SDK gate declaration under a node_modules
        # layout so ``import ... from "@exepad/sdk"`` resolves to our
        # typed surface (useModel/useHandler/setState/navigate
        # constraints, JSX components as `any`).
        #
        # Subpaths: the ``component_sdk_subpaths`` auto-fixer rewrites the bare
        # barrel into ``@exepad/sdk/core``, ``@exepad/sdk/charts``, … imports.
        # Each subpath ``.d.ts`` just re-exports the ambient gate module, and
        # the ``exports`` map lets ``moduleResolution: Bundler`` find them — so
        # ``useModel('x')`` narrowing still flows through (verified) and a
        # mistyped subpath name surfaces as TS2307 rather than silently passing.
        sdk_dir = tmp / "node_modules" / "@exepad" / "sdk"
        sdk_dir.mkdir(parents=True, exist_ok=True)
        (sdk_dir / "index.d.ts").write_bytes(_AGENT_SDK_GATE_DTS.read_bytes())
        exports_map: dict[str, dict[str, str]] = {".": {"types": "./index.d.ts"}}
        for entry in _SDK_SUBPATH_ENTRIES:
            (sdk_dir / f"{entry}.d.ts").write_text(
                'export * from "@exepad/sdk";\n', encoding="utf-8"
            )
            exports_map[f"./{entry}"] = {"types": f"./{entry}.d.ts"}
        (sdk_dir / "package.json").write_text(
            json.dumps({"name": "@exepad/sdk", "types": "index.d.ts", "exports": exports_map}),
            encoding="utf-8",
        )

        (tmp / "tsconfig.json").write_text(
            json.dumps(_TSCONFIG_TEMPLATE, indent=2),
            encoding="utf-8",
        )

        try:
            result = subprocess.run(
                ["tsc", "--noEmit", "--project", str(tmp / "tsconfig.json")],
                capture_output=True,
                text=True,
                timeout=_TSC_TIMEOUT_SECONDS,
                cwd=str(tmp),
            )
        except FileNotFoundError:
            # Production fails loud: the Dockerfile vendors Node + tsc, so a
            # missing binary means the container is misconfigured. Dev
            # continues to fail open so contributors without Node.js can
            # iterate on the rest of the pipeline.
            require_in_production(
                dependency="tsc",
                hint=(
                    "The Dockerfile vendors Node.js + tsc — a missing "
                    "binary means the container build is broken. Refusing "
                    "to validate components with no type-check."
                ),
            )
            return []
        except subprocess.TimeoutExpired:
            return [
                Finding(
                    rule_id="tsc.timeout",
                    severity="error",
                    message=(
                        f"tsc --noEmit timed out (>{_TSC_TIMEOUT_SECONDS}s) "
                        f"on {component_name} — check for circular type imports"
                    ),
                    line=1,
                    col=0,
                )
            ]

        if result.returncode == 0:
            return []
        return list(_parse_diagnostics(result.stdout, component_name))


def _parse_diagnostics(stdout: str, component_name: str) -> Iterable[Finding]:
    """Convert tsc's stdout into Finding objects."""
    for line in stdout.splitlines():
        m = _TSC_DIAGNOSTIC_RE.match(line.strip())
        if m is None:
            continue
        file_name = m.group("file").strip()
        # Only surface diagnostics from the user's component file.
        # Library / SDK type-issue diagnostics are filtered by
        # ``skipLibCheck`` already; this guards against any leftover.
        if not file_name.endswith(f"{component_name}.tsx"):
            continue
        yield Finding(
            rule_id=f"tsc.{m.group('code')}",
            severity="error",
            message=m.group("msg").strip(),
            line=int(m.group("line")),
            col=int(m.group("col")),
        )
