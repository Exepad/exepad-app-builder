"""Run ``tsc --noEmit`` against a generated component.

Per-component flow (called from ``syntax_validator`` as Stage 1.5):

1. Write the component source to a tempdir as ``Component.tsx``.
2. Write the generated per-app ``app.d.ts`` next to it.
3. Copy the SDK's public types (``packages/exepad-sdk/src/index.ts``)
   so module augmentation resolves.
4. Write a minimal ``tsconfig.json`` that includes both files.
5. Invoke ``tsc --noEmit`` (timeout 10 s).
6. Parse stdout / stderr lines into :class:`Finding` objects.

Graceful fallbacks:
- ``tsc`` binary not present (``FileNotFoundError``) → returns ``[]``
  in development (local dev without Node.js stays unblocked).
  **Production raises** :class:`ProductionDependencyMissing` so a
  misconfigured container fails its health check rather than serving
  with type-checking silently disabled. See
  ``services/validation/_env.py``.
- ``tsconfig`` template missing → returns ``[]`` and logs a warning.
- Subprocess timeout (>10 s) → returns a single Finding noting the
  failure rather than crashing the workflow.
"""

from __future__ import annotations

