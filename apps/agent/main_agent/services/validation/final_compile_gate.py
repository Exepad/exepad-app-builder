"""Final Tailwind compile gate — deterministic, no-LLM, runs once at workflow end.

Stages 1 (esbuild syntax), 1.5 (tsc), 2 (semantic + auto-fix) and 4
(style coverage) all run inline by the component save tool. This module
owns the only cross-component step left — the Tailwind v4 compile of
``theme.css`` + every component's classnames into the final stylesheet.

Public entry: :func:`run_final_compile_gate`.

Pipeline:

1. Lift any nested ``@import``/``@source`` directives out of ``@layer``
   blocks (Tailwind v4 rejects them).
2. Lift any nested ``@utility`` blocks to top level (same reason).
3. Ensure the Tailwind bootstrap directives are present at the top of
   theme.css (LLM design imports occasionally drop them).
4. Run ``tailwindcss --input theme.css --output compiled.css`` against
   a temp directory containing all components.
5. If the compile fails, attempt the deterministic ``@apply`` strip and
   the bare-comma syntax fixers as second-chance recovery.
6. Return a :class:`CompileResult` with compiled CSS or fatal errors.
   No retries, no LLM regeneration — the caller decides whether a fatal
   compile error blocks deploy.

The deterministic CSS fixers (``_strip_unknown_apply_classes``,
``_fix_css_syntax_errors``, the lift/inject helpers) are inlined here
because they only run inside this gate.
"""

